insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('charisna-attachments', 'charisna-attachments', false, 20971520, array['application/json'])
on conflict (id) do update set public = false;

drop policy if exists "charisna attachment select own" on storage.objects;
create policy "charisna attachment select own" on storage.objects
for select to authenticated using (
  bucket_id = 'charisna-attachments'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "charisna attachment insert own" on storage.objects;
create policy "charisna attachment insert own" on storage.objects
for insert to authenticated with check (
  bucket_id = 'charisna-attachments'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "charisna attachment update own" on storage.objects;
create policy "charisna attachment update own" on storage.objects
for update to authenticated using (
  bucket_id = 'charisna-attachments'
  and (storage.foldername(name))[1] = (select auth.uid())::text
) with check (
  bucket_id = 'charisna-attachments'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "charisna attachment delete own" on storage.objects;
create policy "charisna attachment delete own" on storage.objects
for delete to authenticated using (
  bucket_id = 'charisna-attachments'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

