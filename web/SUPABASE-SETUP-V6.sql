-- 1) Riwayat versi brankas terenkripsi
create table if not exists public.charisna_vault_versions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  version bigint not null,
  encrypted_vault jsonb not null,
  checksum text,
  device_id text,
  created_at timestamptz not null default now()
);

create index if not exists charisna_vault_versions_user_version_idx
on public.charisna_vault_versions(user_id, version desc);

alter table public.charisna_vault_versions enable row level security;
grant select, insert, delete on public.charisna_vault_versions to authenticated;

drop policy if exists "charisna versions select own" on public.charisna_vault_versions;
create policy "charisna versions select own" on public.charisna_vault_versions
for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "charisna versions insert own" on public.charisna_vault_versions;
create policy "charisna versions insert own" on public.charisna_vault_versions
for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "charisna versions delete own" on public.charisna_vault_versions;
create policy "charisna versions delete own" on public.charisna_vault_versions
for delete to authenticated using ((select auth.uid()) = user_id);

-- 2) Antrean undangan shared wallet
create table if not exists public.charisna_wallet_invites (
  id uuid primary key default gen_random_uuid(),
  wallet_id text not null,
  wallet_name text not null,
  inviter_user_id uuid not null references auth.users(id) on delete cascade,
  invited_email text not null,
  role text not null default 'viewer',
  status text not null default 'pending',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.charisna_wallet_invites enable row level security;
grant select, insert, update, delete on public.charisna_wallet_invites to authenticated;

drop policy if exists "charisna invite owner or recipient select" on public.charisna_wallet_invites;
create policy "charisna invite owner or recipient select" on public.charisna_wallet_invites
for select to authenticated using (
  (select auth.uid()) = inviter_user_id
  or lower(invited_email) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
);

drop policy if exists "charisna invite owner insert" on public.charisna_wallet_invites;
create policy "charisna invite owner insert" on public.charisna_wallet_invites
for insert to authenticated with check ((select auth.uid()) = inviter_user_id);

drop policy if exists "charisna invite owner or recipient update" on public.charisna_wallet_invites;
create policy "charisna invite owner or recipient update" on public.charisna_wallet_invites
for update to authenticated using (
  (select auth.uid()) = inviter_user_id
  or lower(invited_email) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
) with check (
  (select auth.uid()) = inviter_user_id
  or lower(invited_email) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
);

drop policy if exists "charisna invite owner delete" on public.charisna_wallet_invites;
create policy "charisna invite owner delete" on public.charisna_wallet_invites
for delete to authenticated using ((select auth.uid()) = inviter_user_id);

