-- CHARISNA Money Management v10
-- Push subscriptions, reminder schedules, and delivery log.
-- Safe to run more than once.

create table if not exists public.charisna_push_subscriptions (
  endpoint text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  p256dh text not null,
  auth text not null,
  device_id text,
  user_agent text,
  timezone text not null default 'Asia/Jakarta',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists charisna_push_subscriptions_user_idx
  on public.charisna_push_subscriptions(user_id);

create table if not exists public.charisna_bill_reminder_schedules (
  user_id uuid not null references auth.users(id) on delete cascade,
  recurring_id text not null,
  title text not null default 'Tagihan CHARISNA',
  amount numeric,
  currency text,
  due_date date not null,
  reminder_days integer[] not null default array[7,3,1,0],
  notification_time time not null default '08:00',
  timezone text not null default 'Asia/Jakarta',
  privacy_mode text not null default 'generic' check (privacy_mode in ('generic','detailed')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, recurring_id)
);

create index if not exists charisna_bill_reminder_due_idx
  on public.charisna_bill_reminder_schedules(enabled, due_date);

create table if not exists public.charisna_push_delivery_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recurring_id text not null,
  due_date date not null,
  reminder_offset integer not null,
  delivered_at timestamptz not null default now(),
  success_count integer not null default 0,
  failure_count integer not null default 0,
  unique (user_id, recurring_id, due_date, reminder_offset)
);

alter table public.charisna_push_subscriptions enable row level security;
alter table public.charisna_bill_reminder_schedules enable row level security;
alter table public.charisna_push_delivery_log enable row level security;

grant select, insert, update, delete on public.charisna_push_subscriptions to authenticated;
grant select, insert, update, delete on public.charisna_bill_reminder_schedules to authenticated;
grant select on public.charisna_push_delivery_log to authenticated;

-- Push subscriptions

drop policy if exists "Users manage own push subscriptions" on public.charisna_push_subscriptions;
create policy "Users manage own push subscriptions"
on public.charisna_push_subscriptions
for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

-- Bill reminder schedules

drop policy if exists "Users manage own reminder schedules" on public.charisna_bill_reminder_schedules;
create policy "Users manage own reminder schedules"
on public.charisna_bill_reminder_schedules
for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

-- Delivery logs can only be read by their owner. Inserts are performed by Edge Function service role.

drop policy if exists "Users read own push delivery log" on public.charisna_push_delivery_log;
create policy "Users read own push delivery log"
on public.charisna_push_delivery_log
for select to authenticated
using ((select auth.uid()) = user_id);

-- Optional automatic timestamp helper.
create or replace function public.charisna_set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists charisna_push_subscriptions_updated_at on public.charisna_push_subscriptions;
create trigger charisna_push_subscriptions_updated_at
before update on public.charisna_push_subscriptions
for each row execute function public.charisna_set_updated_at();

drop trigger if exists charisna_bill_schedules_updated_at on public.charisna_bill_reminder_schedules;
create trigger charisna_bill_schedules_updated_at
before update on public.charisna_bill_reminder_schedules
for each row execute function public.charisna_set_updated_at();
